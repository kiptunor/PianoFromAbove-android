/*
Followed type convention from Magicalbat
*/

#ifndef MB_TYPES_H
#define MB_TYPES_H

#include <stdint.h>

typedef int64_t            i64;
typedef int32_t            i32;
typedef int16_t            i16;
typedef int8_t             i8;
typedef uint64_t           u64;
typedef uint32_t           u32;
typedef uint16_t           u16;
typedef uint8_t            u8;
typedef float               f32;
typedef double             f64;
typedef unsigned short     us_short;
typedef unsigned int       us_int;
typedef unsigned long      us_long;
typedef unsigned long long us_long2;
typedef unsigned char      us_char;
#endif
